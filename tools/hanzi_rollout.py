"""Roll-out report for the stroke-order mode (Hanzi Writer): which lessons would be affected and what it costs.

    python3 tools/hanzi_rollout.py            prints Markdown (docs/hanzi-writer-rollout.md is this output)

Read-only: it changes no lesson. Per lesson it lists the characters the Writing tab practises (D.chars of generated lessons,
`var CHARS=[...]` of the hand-built lessons 6-8), whether stroke data is vendored for each, and the sizes involved."""
import os,re,json,glob,subprocess
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V=os.path.join(ROOT,'vendor','hanzi-writer')
HAN=re.compile('[㐀-䶿一-鿿]')
def read(p): return open(os.path.join(ROOT,p),encoding='utf8').read()
def title(s): return re.search(r'<title>(.*?)</title>',s,re.S).group(1).strip()
def chars_of(s):
    m=re.search(r'var D=(\{.*?\});\n(?:var X=|var VOCAB=D\.vocab)',s,re.S)
    D=json.loads(re.search(r'var D=(.*?);\nvar VOCAB=D\.vocab',s,re.S).group(1).replace('<\\/','</'))
    if D.get('chars'): return [c['c'] for c in D['chars']],'generated'
    m=re.search(r'var CHARS=\[(.*?)\n\];',s,re.S)          # hand-built lessons 6-8 (frozen snippets)
    return (re.findall(r"""\bc:\s*['"]([^'"])['"]""",m.group(1)) if m else []),'hand-built'
def dsize(c):
    f=os.path.join(V,'data','%x.json'%ord(c));return os.path.getsize(f) if os.path.exists(f) else None
def strokes(c):
    f=os.path.join(V,'data','%x.json'%ord(c));return len(json.load(open(f,encoding='utf8'))['strokes']) if os.path.exists(f) else None
def git_size(path):
    try: return len(subprocess.check_output(['git','show','origin/main:'+path],cwd=ROOT,stderr=subprocess.DEVNULL))
    except Exception: return None

groups=[('Grammar 1 / Foreign Language','lesson-*.html'),('Reading 1','prac-*.html'),('Listening 1','lis-*.html'),('Practical Chinese','biz-*.html'),('Chinese Culture','cult-*.html')]
def num(p): return int(re.search(r'-(\d+)\.html',p).group(1))
rows=[];union=set()
for g,pat in groups:
    for p in sorted(glob.glob(os.path.join(ROOT,pat)),key=num):
        rel=os.path.basename(p);s=read(rel)
        has_tab='data-tab="writing"' in s
        if not has_tab: rows.append((g,rel,title(s),None,'no Writing tab',[]));continue
        ch,kind=chars_of(s)
        status='ON (sample)' if '"hw":1' in s else kind
        rows.append((g,rel,title(s),kind,status,ch))
        if '"hw":1' not in s: union|=set(ch)
allvend=sum(os.path.getsize(os.path.join(V,'data',f)) for f in os.listdir(os.path.join(V,'data')))
nvend=len(os.listdir(os.path.join(V,'data')))
need=set();
for r in rows: need|=set(r[5])
need_bytes=sum(dsize(c) or 0 for c in need)
miss=[c for c in need if dsize(c) is None]
out=[]
w=out.append
w('# Stroke-order mode (Hanzi Writer): roll-out report\n')
w('Generated by `python3 tools/hanzi_rollout.py`. Nothing here is switched on yet except the Lesson 9 sample.\n')
w('## Summary\n')
w('- Lessons with a Writing tab that could get the mode: **%d** (Lesson 9 is the sample); culture lessons have no Writing tab, so the mode does not apply to them.'%sum(1 for r in rows if r[3]))
w('- Characters practised in those Writing tabs: **%d distinct** (%d still to roll out). Stroke data present for **%d of %d**%s.'%(len(need),len(union),len(need)-len(miss),len(need),(' (missing: '+''.join(miss)+')') if miss else ''))
w('- **Extra repository size to roll out: 0 bytes of data.** `vendor/hanzi-writer/` already holds stroke data for all %d characters that occur anywhere in the lesson pages (%.2f MB, %d files); the Writing-tab characters are %d of them (%.2f MB). Switching a lesson on is one line in its data module plus a rebuild (+10 bytes in its page).'%(nvend,allvend/1e6,nvend,len(need),need_bytes/1e6))
w('- Optional saving: if stroke order is only ever used on the Writing tab, the vendored data could be pruned to those %d characters, saving **%.2f MB** (%.0f%%) of repository size; it would then need re-running `tools/hanzi_data.py` whenever the practised characters change. Keeping all %d characters covers future uses (for example stroke order from vocabulary cards) without more downloads.'%(len(need),(allvend-need_bytes)/1e6,100*(allvend-need_bytes)/allvend,nvend))
w('- Page size: the mode\'s code is already in every generated page (it is inert unless the lesson opts in); the roll-out itself adds nothing measurable.\n')
w('## Per lesson\n')
w('| Lesson | Title | Writing-tab characters | Count | Data | Effort to switch on |')
w('|---|---|---|---|---|---|')
for g,rel,t,kind,status,ch in rows:
    if kind is None: w('| %s | %s | - | - | - | not applicable (no Writing tab) |'%(rel,t));continue
    d='yes' if all(dsize(c) for c in ch) else 'MISSING: '+''.join(c for c in ch if not dsize(c))
    eff={'generated':'one line (`L[\'hanzi_writer\']=True`) + rebuild','hand-built':'small extra work: its writing section is a frozen snippet (`tools/lsn3/legacy/g*.writing.js`) that must call the new code'}.get(kind,'-') if status!='ON (sample)' else 'done (sample)'
    w('| %s | %s | %s | %d | %s | %s |'%(rel,t,' '.join(ch),len(ch),d,eff))
w('')
w('## Suggested order (your call)\n')
w('1. Generated lessons, course by course, each a one-line change with its own test run: Grammar 1 / Foreign Language lesson 10, then Reading 6-10, Listening 6-10, Practical Chinese 4-6.')
w('2. Hand-built lessons 6, 7, 8 last: their Writing section needs a small adaptation (call the stroke-order code from their snippet) and a comparison against the current page.')
w('3. After each batch: run `node tools/lsn3/t9.js` (extended to the new lessons) and the other suites, and check the preview on a phone.\n')
w('## Characters per course (union of the Writing tabs)\n')
for g,pat in groups:
    cs=[];seen=set()
    for r in rows:
        if r[0]==g:
            for c in r[5]:
                if c not in seen: seen.add(c);cs.append(c)
    if cs: w('- **%s**: %d characters: %s'%(g,len(cs),' '.join(cs)))
print('\n'.join(out))
