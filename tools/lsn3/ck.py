sys.path.insert(0,'.')
def load(n):
    return importlib.import_module('cl%d'%n).L
LS={n:load(n) for n in (1,2,3,4)}
def strings(L):
    out=[]
    for s in L['sections']:
        for b in s['b']:
            k=list(b.keys())[0];v=b[k]
            if k in('p','key'): out.append(v)
            elif k=='ul': out+=v
            elif k=='tl': out+=[x[1] for x in v]+[x[0]+'，'+x[1] for x in v]
            elif k=='cards': out+=[x[2] for x in v if x[2]]
    return out
def F(n,sub):
    for s in strings(LS[n]):
        if sub in s: return s
    raise KeyError((n,sub))
def card(n,zh):
    for s in LS[n]['sections']:
        for b in s['b']:
            if 'cards' in b:
                for c in b['cards']:
                    if c[0]==zh: return c
    raise KeyError(zh)
def D_(n,zh,group,name=None,defn=None):
    c=None
    try: c=card(n,zh)
    except KeyError: pass
    return {'zh':zh,'name':name or (c[1] if c else ''),'def':defn or (c[2] if c else ''),'g':group}
